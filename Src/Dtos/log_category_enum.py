from enum import Enum

"""
Категории операций, учитываемых в журнале системы
"""
class log_category_enum(Enum):

    """
    CRUD операции с доменными сущностями (создание, изменение, удаление)
    """
    CRUD = "CRUD"

    """
    Складские операции (движения и остатки, операции со складскими сущностями)
    """
    WAREHOUSE = "WAREHOUSE"

    """
    Вызовы web методов (входящие запросы REST API)
    """
    WEB = "WEB"

    """
    Изменение параметров настроек
    """
    SETTINGS = "SETTINGS"

    """
    Текстовое представление категории
    """
    def __str__(self) -> str:
        return self.value
